export type PixelIconName = keyof typeof ICONS;

/** Every filled cell as [x, y]; computed once per icon. */
const CELLS = Object.fromEntries(
  Object.entries(ICONS).map(([name, rows]) => [
    name,
    rows.flatMap((row, y) => [...row].flatMap((cell, x) => (cell === "#" ? [[x, y] as const] : []))),
  ]),
) as unknown as Record<PixelIconName, readonly (readonly [number, number])[]>;

export function PixelIcon({
  name,
  size = 18,
  className,
}: {
  name: PixelIconName;
  size?: number;
  className?: string;
}) {
  return (
    <svg
      className={className ? `pixel-icon ${className}` : "pixel-icon"}
      width={size}
      height={size}
      viewBox="0 0 9 9"
      shapeRendering="crispEdges"
      fill="currentColor"
      aria-hidden="true"
    >
      {CELLS[name].map(([x, y]) => (
        <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} />
      ))}
    </svg>
  );
}
